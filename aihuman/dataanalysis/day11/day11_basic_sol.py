# 폴더와 파일 경로 처리를 위해 os 모듈을 불러옵니다.
import os

# 데이터 처리를 위해 pandas를 pd라는 별칭으로 불러옵니다.
import pandas as pd


# ------------------------------------------------------------
# 과제용 CSV 파일 생성
# ------------------------------------------------------------

# CSV 파일을 저장할 폴더를 지정합니다.
assets_dir = "./assets"

# 폴더가 없으면 생성합니다.
os.makedirs(assets_dir, exist_ok=True)

# 원본 CSV 파일의 경로를 지정합니다.
csv_path = os.path.join(assets_dir, "day11_library_raw.csv")

# 도서관 대출 데이터를 딕셔너리로 작성합니다.
library_data = {
    "대출ID": ["L001", "L002", "L003", "L004", "L005", "L002", "L006"],
    "도서분류": ["IT", "경제", "문학", "IT", "과학", "경제", "문학"],
    "대출일수": ["7", "14", "10", "unknown", "21", "14", "7"],
    "연체일수": [0, 3, 0, 2, 5, 3, 0],
    "회원등급": ["일반", "우수", None, "일반", "우수", "우수", "일반"],
}

# 딕셔너리를 DataFrame으로 변환합니다.
source_df = pd.DataFrame(library_data)

# DataFrame을 CSV 파일로 저장합니다.
source_df.to_csv(csv_path, index=False, encoding="utf-8-sig")


# ------------------------------------------------------------
# 원본 데이터 읽기와 확인
# ------------------------------------------------------------

# CSV 파일을 읽어 DataFrame으로 만듭니다.
df = pd.read_csv(csv_path, encoding="utf-8-sig")

# 원본 데이터의 앞부분을 출력합니다.
print("\n[원본 데이터]")
print(df.head())

# 원본 행 수와 열 수를 출력합니다.
print("\n[원본 shape]")
print(df.shape)

# 원본 컬럼별 자료형을 출력합니다.
print("\n[원본 dtype]")
print(df.dtypes)


# ------------------------------------------------------------
# loc와 iloc 조회
# ------------------------------------------------------------

# 연체일수가 1일 이상인 행에서 필요한 컬럼만 선택합니다.
overdue_rows = df.loc[
    df["연체일수"] >= 1,
    ["대출ID", "도서분류", "연체일수"],
]

# 연체 데이터를 출력합니다.
print("\n[연체일수 1일 이상]")
print(overdue_rows)

# 앞 4행과 앞 3열을 위치 기준으로 선택합니다.
position_rows = df.iloc[0:4, 0:3]

# iloc 조회 결과를 출력합니다.
print("\n[앞 4행, 앞 3열]")
print(position_rows)


# ------------------------------------------------------------
# 결측치와 중복 확인
# ------------------------------------------------------------

# 컬럼별 결측치 개수를 출력합니다.
print("\n[컬럼별 결측치]")
print(df.isna().sum())

# 전체 중복 행 수를 계산합니다.
duplicate_count = df.duplicated().sum()

# 중복 행 수를 출력합니다.
print("\n[중복 행 수]")
print(duplicate_count)


# ------------------------------------------------------------
# 자료형 변환과 결측치 처리
# ------------------------------------------------------------

# 대출일수를 숫자로 변환하고 변환할 수 없는 값은 NaN으로 바꿉니다.
df["대출일수"] = pd.to_numeric(df["대출일수"], errors="coerce")

# 대출일수의 중앙값을 계산합니다.
loan_days_median = df["대출일수"].median()

# 대출일수 결측치를 중앙값으로 대체합니다.
df["대출일수"] = df["대출일수"].fillna(loan_days_median)

# 회원등급 결측치를 일반으로 대체합니다.
df["회원등급"] = df["회원등급"].fillna("일반")


# ------------------------------------------------------------
# 중복 제거와 최종 dtype 정리
# ------------------------------------------------------------

# 완전히 동일한 중복 행을 제거합니다.
df = df.drop_duplicates()

# Index를 0부터 다시 정리합니다.
df = df.reset_index(drop=True)

# 대출일수를 정수형으로 변환합니다.
df["대출일수"] = df["대출일수"].astype("int64")


# ------------------------------------------------------------
# 최종 결과 확인
# ------------------------------------------------------------

# 전처리된 전체 데이터를 출력합니다.
print("\n[전처리 완료 데이터]")
print(df)

# 전처리 후 shape를 출력합니다.
print("\n[전처리 후 shape]")
print(df.shape)

# 전처리 후 컬럼별 결측치 개수를 출력합니다.
print("\n[전처리 후 결측치]")
print(df.isna().sum())

# 전처리 후 중복 행 수를 출력합니다.
print("\n[전처리 후 중복 행 수]")
print(df.duplicated().sum())

# 전처리 후 dtype을 출력합니다.
print("\n[전처리 후 dtype]")
print(df.dtypes)
