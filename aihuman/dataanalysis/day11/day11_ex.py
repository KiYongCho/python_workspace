# 폴더와 파일 경로를 다루기 위해 os 모듈을 불러옵니다.
import os

# 표 형태의 데이터를 처리하기 위해 pandas를 pd라는 별칭으로 불러옵니다.
import pandas as pd


# ------------------------------------------------------------
# 실습용 데이터 파일 준비
# ------------------------------------------------------------

# CSV 파일을 저장할 assets 폴더 경로를 지정합니다.
assets_dir = "./assets"

# assets 폴더가 없으면 새로 생성합니다.
os.makedirs(assets_dir, exist_ok=True)

# 원본 고객 문의 CSV 파일의 경로를 지정합니다.
raw_csv_path = os.path.join(assets_dir, "day11_customer_inquiry_raw.csv")

# 정제한 고객 문의 CSV 파일의 경로를 지정합니다.
clean_csv_path = os.path.join(assets_dir, "day11_customer_inquiry_clean.csv")

# 결측치, 중복, 혼합 자료형이 포함된 실습용 데이터를 딕셔너리로 준비합니다.
sample_data = {
    "문의ID": ["Q001", "Q002", "Q003", "Q004", "Q005", "Q006", "Q002", "Q007", "Q008", "Q009"],
    "지역": ["서울", "부산", "서울", "대전", None, "서울", "부산", "인천", "서울", "대구"],
    "문의유형": ["결제", "배송", "환불", "결제", "배송", "환불", "배송", "회원", "배송", "결제"],
    "처리시간": ["12", "8", "15", "unknown", "20", "10", "8", None, "18", "13"],
    "만족도": [5, 4, None, 3, 4, 5, 4, None, 2, 4],
    "담당자": ["김대리", "이주임", "박대리", None, "최과장", "김대리", "이주임", "정대리", None, "박대리"],
}

# 실습용 딕셔너리를 DataFrame으로 변환합니다.
sample_df = pd.DataFrame(sample_data)

# 원본 형태를 CSV 파일로 저장합니다.
sample_df.to_csv(raw_csv_path, index=False, encoding="utf-8-sig")


# ------------------------------------------------------------
# 원본 데이터 읽기와 기본 점검
# ------------------------------------------------------------

# CSV 파일을 읽어 DataFrame으로 만듭니다.
df = pd.read_csv(raw_csv_path, encoding="utf-8-sig")

# 전처리 이전 상태를 나중에 비교하기 위해 깊은 복사본을 만듭니다.
before_df = df.copy()

# 데이터 앞부분을 확인합니다.
print("\n[원본 데이터]")
print(df.head())

# 전체 행 수와 열 수를 확인합니다.
print("\n[원본 shape]")
print(df.shape)

# 전체 컬럼명을 확인합니다.
print("\n[컬럼명]")
print(df.columns.tolist())

# 컬럼별 자료형을 확인합니다.
print("\n[원본 dtype]")
print(df.dtypes)


# ------------------------------------------------------------
# loc를 이용한 레이블·조건 기반 조회
# ------------------------------------------------------------

# loc를 이용해 0번부터 2번 Index까지 필요한 컬럼만 선택합니다.
loc_sample = df.loc[0:2, ["문의ID", "지역", "만족도"]]

# loc 조회 결과를 출력합니다.
print("\n[loc 조회 - 0~2번 Index]")
print(loc_sample)

# 지역이 서울인 행에서 일부 컬럼만 선택합니다.
seoul_rows = df.loc[df["지역"] == "서울", ["문의ID", "문의유형", "처리시간"]]

# 조건을 적용한 loc 결과를 출력합니다.
print("\n[loc 조건 조회 - 서울 지역]")
print(seoul_rows)


# ------------------------------------------------------------
# iloc를 이용한 위치 기반 조회
# ------------------------------------------------------------

# iloc를 이용해 앞 3개 행과 앞 3개 열을 선택합니다.
iloc_sample = df.iloc[0:3, 0:3]

# iloc 조회 결과를 출력합니다.
print("\n[iloc 조회 - 앞 3행, 앞 3열]")
print(iloc_sample)


# ------------------------------------------------------------
# 결측치 진단
# ------------------------------------------------------------

# 컬럼별 결측치 개수를 계산합니다.
missing_by_column = df.isna().sum()

# 컬럼별 결측치 개수를 출력합니다.
print("\n[컬럼별 결측치 개수]")
print(missing_by_column)

# 전체 결측치 개수를 계산합니다.
missing_total_before = df.isna().sum().sum()

# 전체 결측치 개수를 출력합니다.
print("\n[전체 결측치 개수]")
print(missing_total_before)

# 하나 이상의 결측치가 있는 행을 선택합니다.
rows_with_missing = df.loc[df.isna().any(axis=1)]

# 결측치가 있는 행을 출력합니다.
print("\n[결측치가 있는 행]")
print(rows_with_missing)


# ------------------------------------------------------------
# 중복 데이터 진단
# ------------------------------------------------------------

# 완전히 동일한 중복 행인지 각 행별로 확인합니다.
duplicate_flags = df.duplicated()

# 중복 여부를 출력합니다.
print("\n[중복 여부]")
print(duplicate_flags)

# 전체 중복 행 수를 계산합니다.
duplicate_count_before = df.duplicated().sum()

# 중복 행 수를 출력합니다.
print("\n[중복 행 수]")
print(duplicate_count_before)

# 중복된 행만 선택합니다.
duplicate_rows = df.loc[df.duplicated()]

# 중복된 행을 출력합니다.
print("\n[중복된 행]")
print(duplicate_rows)


# ------------------------------------------------------------
# 처리시간 컬럼을 숫자형으로 변환
# ------------------------------------------------------------

# 처리시간 컬럼이 원본에서 어떤 자료형인지 확인합니다.
print("\n[처리시간 변환 전 dtype]")
print(df["처리시간"].dtype)

# 숫자로 변환할 수 없는 값을 NaN으로 바꾸면서 처리시간을 숫자형으로 변환합니다.
df["처리시간"] = pd.to_numeric(df["처리시간"], errors="coerce")

# 변환 결과의 자료형을 확인합니다.
print("\n[처리시간 변환 후 dtype]")
print(df["처리시간"].dtype)

# 숫자 변환 후 처리시간 컬럼에 생긴 결측치 개수를 확인합니다.
print("\n[숫자 변환 후 처리시간 결측치]")
print(df["처리시간"].isna().sum())


# ------------------------------------------------------------
# 결측치 처리
# ------------------------------------------------------------

# 처리시간의 중앙값을 계산합니다.
processing_time_median = df["처리시간"].median()

# 처리시간의 결측치를 중앙값으로 대체합니다.
df["처리시간"] = df["처리시간"].fillna(processing_time_median)

# 만족도의 중앙값을 계산합니다.
satisfaction_median = df["만족도"].median()

# 만족도의 결측치를 중앙값으로 대체합니다.
df["만족도"] = df["만족도"].fillna(satisfaction_median)

# 지역 컬럼의 최빈값을 계산합니다.
region_mode = df["지역"].mode()[0]

# 지역의 결측치를 최빈값으로 대체합니다.
df["지역"] = df["지역"].fillna(region_mode)

# 담당자 결측치를 의미가 분명한 고정 문자열로 대체합니다.
df["담당자"] = df["담당자"].fillna("미배정")

# 결측치 처리 후 컬럼별 결측치 개수를 확인합니다.
print("\n[결측치 처리 후]")
print(df.isna().sum())


# ------------------------------------------------------------
# 중복 데이터 제거
# ------------------------------------------------------------

# 완전히 동일한 중복 행을 제거합니다.
df = df.drop_duplicates()

# 중복 제거 후 Index를 0부터 다시 정리합니다.
df = df.reset_index(drop=True)

# 중복 제거 후 행 수를 출력합니다.
print("\n[중복 제거 후 shape]")
print(df.shape)


# ------------------------------------------------------------
# 최종 자료형 정리
# ------------------------------------------------------------

# 처리시간을 정수형으로 변환합니다.
df["처리시간"] = df["처리시간"].astype("int64")

# 만족도를 정수형으로 변환합니다.
df["만족도"] = df["만족도"].astype("int64")

# 최종 컬럼별 자료형을 출력합니다.
print("\n[최종 dtype]")
print(df.dtypes)


# ------------------------------------------------------------
# 전처리 결과 조건 조회
# ------------------------------------------------------------

# 만족도가 4점 이상이고 처리시간이 15분 이하인 행을 선택합니다.
good_service = df.loc[
    (df["만족도"] >= 4) & (df["처리시간"] <= 15),
    ["문의ID", "지역", "문의유형", "처리시간", "만족도"],
]

# 조건에 맞는 문의 데이터를 출력합니다.
print("\n[만족도 4점 이상 & 처리시간 15분 이하]")
print(good_service)


# ------------------------------------------------------------
# 전처리 전후 비교
# ------------------------------------------------------------

# 전처리 이전 행 수를 계산합니다.
rows_before = before_df.shape[0]

# 전처리 이후 행 수를 계산합니다.
rows_after = df.shape[0]

# 전처리 이후 전체 결측치 개수를 계산합니다.
missing_total_after = df.isna().sum().sum()

# 전처리 이후 중복 행 수를 계산합니다.
duplicate_count_after = df.duplicated().sum()

# 전처리 전후 비교 내용을 DataFrame으로 만듭니다.
comparison_df = pd.DataFrame(
    {
        "점검항목": ["행 수", "전체 결측치", "중복 행"],
        "전처리전": [rows_before, missing_total_before, duplicate_count_before],
        "전처리후": [rows_after, missing_total_after, duplicate_count_after],
    }
)

# 전처리 전후 비교표를 출력합니다.
print("\n[전처리 전후 비교표]")
print(comparison_df)


# ------------------------------------------------------------
# 정제 데이터의 기본 통계 확인
# ------------------------------------------------------------

# 처리시간과 만족도의 기술통계를 출력합니다.
print("\n[정제 후 기술통계]")
print(df[["처리시간", "만족도"]].describe())


# ------------------------------------------------------------
# 정제된 데이터 저장
# ------------------------------------------------------------

# 최종 정제 DataFrame을 새로운 CSV 파일로 저장합니다.
df.to_csv(clean_csv_path, index=False, encoding="utf-8-sig")

# 저장 결과와 파일 경로를 출력합니다.
print("\n[정제 데이터 저장 완료]")
print(clean_csv_path)
