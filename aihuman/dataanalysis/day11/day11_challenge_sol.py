# 폴더와 파일 경로를 다루기 위해 os 모듈을 불러옵니다.
import os

# 데이터 전처리를 위해 pandas를 pd라는 별칭으로 불러옵니다.
import pandas as pd


# ------------------------------------------------------------
# 원본 주문 데이터 생성
# ------------------------------------------------------------

# 파일 저장 폴더를 지정합니다.
assets_dir = "./assets"

# 폴더가 없으면 생성합니다.
os.makedirs(assets_dir, exist_ok=True)

# 원본 주문 CSV 파일 경로를 지정합니다.
raw_path = os.path.join(assets_dir, "day11_orders_raw.csv")

# 정제된 주문 CSV 파일 경로를 지정합니다.
clean_path = os.path.join(assets_dir, "day11_orders_clean.csv")

# 결측치, 중복, 오류값이 포함된 주문 데이터를 작성합니다.
order_data = {
    "주문ID": ["O2001", "O2002", "O2003", "O2004", "O2005", "O2002", "O2006", "O2007", "O2008"],
    "상품분류": ["노트북", "마우스", "키보드", "모니터", "헤드셋", "마우스", "웹캠", "노트북", "마우스"],
    "수량": ["1", "2", "unknown", "1", "2", "2", None, "1", "3"],
    "결제금액": ["1200000", "44000", "65000", "350000", "오류", "44000", "98000", "1350000", "66000"],
    "채널": ["웹", "앱", "앱", None, "웹", "앱", "앱", "웹", "앱"],
    "고객등급": ["Gold", "Silver", "Silver", "Gold", None, "Silver", "Bronze", "Gold", "Silver"],
}

# 주문 데이터를 DataFrame으로 변환합니다.
source_df = pd.DataFrame(order_data)

# 원본 DataFrame을 CSV로 저장합니다.
source_df.to_csv(raw_path, index=False, encoding="utf-8-sig")


# ------------------------------------------------------------
# 원본 데이터 읽기와 점검
# ------------------------------------------------------------

# 원본 CSV 파일을 읽습니다.
df = pd.read_csv(raw_path, encoding="utf-8-sig")

# 전처리 전 비교용 복사본을 만듭니다.
before_df = df.copy()

# 전처리 전 행 수를 계산합니다.
rows_before = before_df.shape[0]

# 전처리 전 전체 결측치 수를 계산합니다.
missing_before = before_df.isna().sum().sum()

# 주문ID 기준 중복 수를 계산합니다.
duplicate_order_before = before_df.duplicated(subset=["주문ID"]).sum()

# 원본 dtype을 출력합니다.
print("\n[원본 dtype]")
print(before_df.dtypes)

# 원본 컬럼별 결측치를 출력합니다.
print("\n[원본 결측치]")
print(before_df.isna().sum())

# 원본 중복 주문ID 수를 출력합니다.
print("\n[원본 중복 주문ID]")
print(duplicate_order_before)


# ------------------------------------------------------------
# loc와 iloc 데이터 조회
# ------------------------------------------------------------

# 앱 채널 주문에서 필요한 컬럼만 선택합니다.
app_orders = df.loc[
    df["채널"] == "앱",
    ["주문ID", "수량", "결제금액"],
]

# 앱 주문을 출력합니다.
print("\n[앱 채널 주문]")
print(app_orders)

# 앞 5행과 앞 4열을 위치 기준으로 선택합니다.
first_block = df.iloc[0:5, 0:4]

# iloc 조회 결과를 출력합니다.
print("\n[앞 5행, 앞 4열]")
print(first_block)


# ------------------------------------------------------------
# 숫자형 변환
# ------------------------------------------------------------

# 수량을 숫자로 변환하고 변환할 수 없는 값은 NaN으로 바꿉니다.
df["수량"] = pd.to_numeric(df["수량"], errors="coerce")

# 결제금액을 숫자로 변환하고 변환할 수 없는 값은 NaN으로 바꿉니다.
df["결제금액"] = pd.to_numeric(df["결제금액"], errors="coerce")

# 숫자 변환 직후 수량 결측치 수를 출력합니다.
print("\n[숫자 변환 후 수량 결측치]")
print(df["수량"].isna().sum())

# 숫자 변환 직후 결제금액 결측치 수를 출력합니다.
print("\n[숫자 변환 후 결제금액 결측치]")
print(df["결제금액"].isna().sum())


# ------------------------------------------------------------
# 결측치 처리
# ------------------------------------------------------------

# 수량의 중앙값을 계산합니다.
quantity_median = df["수량"].median()

# 수량 결측치를 중앙값으로 대체합니다.
df["수량"] = df["수량"].fillna(quantity_median)

# 결제금액의 중앙값을 계산합니다.
payment_median = df["결제금액"].median()

# 결제금액 결측치를 중앙값으로 대체합니다.
df["결제금액"] = df["결제금액"].fillna(payment_median)

# 채널 결측치를 미확인으로 대체합니다.
df["채널"] = df["채널"].fillna("미확인")

# 고객등급의 최빈값을 계산합니다.
grade_mode = df["고객등급"].mode()[0]

# 고객등급 결측치를 최빈값으로 대체합니다.
df["고객등급"] = df["고객등급"].fillna(grade_mode)


# ------------------------------------------------------------
# 주문ID 기준 중복 제거
# ------------------------------------------------------------

# 주문ID를 기준으로 첫 번째 주문만 남기고 중복을 제거합니다.
df = df.drop_duplicates(subset=["주문ID"], keep="first")

# Index를 0부터 다시 정리합니다.
df = df.reset_index(drop=True)


# ------------------------------------------------------------
# 최종 자료형 정리
# ------------------------------------------------------------

# 수량을 정수형으로 변환합니다.
df["수량"] = df["수량"].astype("int64")

# 결제금액을 정수형으로 변환합니다.
df["결제금액"] = df["결제금액"].astype("int64")


# ------------------------------------------------------------
# 고액 주문 조회
# ------------------------------------------------------------

# 결제금액이 50,000원 이상인 주문을 선택합니다.
high_value_orders = df.loc[
    df["결제금액"] >= 50000,
    ["주문ID", "상품분류", "수량", "결제금액", "채널"],
]

# 고액 주문을 출력합니다.
print("\n[50,000원 이상 주문]")
print(high_value_orders)


# ------------------------------------------------------------
# 전처리 근거 기록
# ------------------------------------------------------------

# 수량, 결제금액, 채널, 주문ID 중복에 대한 처리 근거를 리스트로 작성합니다.
cleaning_log_rows = [
    {
        "항목": "수량",
        "발견문제": "문자열 unknown과 결측값 포함",
        "처리방법": "숫자 변환 후 중앙값 대체",
        "처리근거": "수량을 집계 가능한 숫자형으로 만들고 오류값의 영향을 제한",
    },
    {
        "항목": "결제금액",
        "발견문제": "문자열 오류값 포함",
        "처리방법": "숫자 변환 후 중앙값 대체",
        "처리근거": "금액 계산이 가능하도록 숫자형을 통일하고 큰 금액의 영향이 적은 중앙값 사용",
    },
    {
        "항목": "채널",
        "발견문제": "일부 채널 값 누락",
        "처리방법": "미확인으로 대체",
        "처리근거": "실제 채널을 임의 추정하지 않고 누락 상태를 별도 범주로 유지",
    },
    {
        "항목": "주문ID 중복",
        "발견문제": "O2002가 반복 저장됨",
        "처리방법": "주문ID 기준 첫 번째 행 유지",
        "처리근거": "동일 주문ID가 동일 내용으로 반복되어 중복 저장으로 판단",
    },
]

# 전처리 근거 리스트를 DataFrame으로 변환합니다.
cleaning_log_df = pd.DataFrame(cleaning_log_rows)

# 전처리 근거표를 출력합니다.
print("\n[전처리 근거]")
print(cleaning_log_df)


# ------------------------------------------------------------
# 전처리 전후 비교
# ------------------------------------------------------------

# 전처리 후 행 수를 계산합니다.
rows_after = df.shape[0]

# 전처리 후 전체 결측치 수를 계산합니다.
missing_after = df.isna().sum().sum()

# 전처리 후 주문ID 중복 수를 계산합니다.
duplicate_order_after = df.duplicated(subset=["주문ID"]).sum()

# 전처리 전후 비교표를 작성합니다.
comparison_df = pd.DataFrame(
    {
        "점검항목": ["행 수", "전체 결측치", "중복 주문ID"],
        "전처리전": [rows_before, missing_before, duplicate_order_before],
        "전처리후": [rows_after, missing_after, duplicate_order_after],
    }
)

# 전처리 전후 비교표를 출력합니다.
print("\n[전처리 전후 비교]")
print(comparison_df)


# ------------------------------------------------------------
# 결제금액 기초 통계
# ------------------------------------------------------------

# 결제금액의 데이터 개수를 계산합니다.
payment_count = df["결제금액"].count()

# 결제금액의 평균을 계산합니다.
payment_mean = df["결제금액"].mean()

# 결제금액의 최솟값을 계산합니다.
payment_min = df["결제금액"].min()

# 결제금액의 최댓값을 계산합니다.
payment_max = df["결제금액"].max()

# 결제금액 통계를 출력합니다.
print("\n[결제금액 통계]")
print(f"count: {payment_count}")
print(f"mean: {payment_mean:,.2f}")
print(f"min: {payment_min:,}")
print(f"max: {payment_max:,}")


# ------------------------------------------------------------
# 정제 데이터 저장
# ------------------------------------------------------------

# 최종 정제 DataFrame을 CSV 파일로 저장합니다.
df.to_csv(clean_path, index=False, encoding="utf-8-sig")

# 저장 경로를 출력합니다.
print("\n[정제 데이터 저장 완료]")
print(clean_path)
