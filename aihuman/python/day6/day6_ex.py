# 8. 리스트를 매개변수로 전달하여 평균 구하기
# ------------------------------------------------------------

# 점수 리스트를 전달받아 평균을 반환하는 함수를 정의합니다.
def get_average(scores):
    # 합계를 저장할 변수를 0으로 초기화합니다.
    total = 0
    # scores 리스트의 값을 하나씩 반복합니다.
    for score in scores:
        # 현재 점수를 total에 누적합니다.
        total += score
    # 총점을 점수 개수로 나눈 평균을 반환합니다.
    return total / len(scores)

# 세 과목 점수를 리스트로 만듭니다.
my_scores = [85, 90, 78]

# 리스트를 함수에 전달하여 평균을 구합니다.
my_average = get_average(my_scores)

# 평균을 소수점 첫째 자리까지 출력합니다.
print(f"평균 = {my_average:.1f}")

# 평균값을 등급 함수에 다시 전달합니다.
my_grade = get_grade(my_average)

# 평균 등급을 출력합니다.
print(f"평균 등급 = {my_grade}")

# 구분선을 출력합니다.
print("-" * 50)


