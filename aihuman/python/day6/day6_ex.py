# 9. 여러 값을 반환하기
# ------------------------------------------------------------

# 두 과목의 총점과 평균을 함께 반환하는 함수를 정의합니다.
def get_total_average(score1, score2):
    # 두 점수의 합을 total에 저장합니다.
    total = score1 + score2
    # 총점을 2로 나누어 average에 저장합니다.
    average = total / 2
    # total과 average 두 값을 함께 반환합니다.
    return total, average

# 반환되는 두 값을 각각 total_score와 average_score에 나누어 저장합니다.
total_score, average_score = get_total_average(88, 92)

# 총점을 출력합니다.
print(f"총점 = {total_score}")

# 평균을 출력합니다.
print(f"평균 = {average_score:.1f}")

# 구분선을 출력합니다.
print("-" * 50)


