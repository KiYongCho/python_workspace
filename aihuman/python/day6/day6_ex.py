# 7. 조건문을 함수로 분리하기
# ------------------------------------------------------------

# 점수를 입력받아 등급을 반환하는 함수를 정의합니다.
def get_grade(score):
    # 점수가 90점 이상인지 확인합니다.
    if score >= 90:
        # 조건을 만족하면 A를 반환하고 함수를 종료합니다.
        return "A"
    # 점수가 80점 이상인지 확인합니다.
    elif score >= 80:
        # 조건을 만족하면 B를 반환합니다.
        return "B"
    # 점수가 70점 이상인지 확인합니다.
    elif score >= 70:
        # 조건을 만족하면 C를 반환합니다.
        return "C"
    # 점수가 60점 이상인지 확인합니다.
    elif score >= 60:
        # 조건을 만족하면 D를 반환합니다.
        return "D"
    # 위 조건을 모두 만족하지 않는 경우입니다.
    else:
        # F를 반환합니다.
        return "F"

# 87점을 함수에 전달하고 등급을 반환받습니다.
grade = get_grade(87)

# 반환받은 등급을 출력합니다.
print(f"87점의 등급 = {grade}")

# 여러 점수를 리스트에 저장합니다.
test_scores = [95, 84, 76, 59]

# 리스트의 각 점수를 반복합니다.
for score in test_scores:
    # 현재 점수를 get_grade 함수에 전달하여 등급을 구합니다.
    current_grade = get_grade(score)
    # 점수와 등급을 함께 출력합니다.
    print(f"{score}점 -> {current_grade}등급")

# 구분선을 출력합니다.
print("-" * 50)


