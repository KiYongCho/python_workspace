# 12. 딕셔너리와 함수를 결합한 학생 처리
# ------------------------------------------------------------

# 학생 한 명의 정보를 딕셔너리로 저장합니다.
student = {
    # name 키에 학생 이름을 저장합니다.
    "name": "김민수",
    # scores 키에 세 과목 점수 리스트를 저장합니다.
    "scores": [85, 90, 78]
}

# 학생 한 명의 결과를 출력하는 함수를 정의합니다.
def print_student_report(student_data):
    # 딕셔너리의 scores 값을 평균 함수에 전달합니다.
    average = get_average(student_data["scores"])
    # 계산된 평균을 등급 함수에 전달합니다.
    grade = get_grade(average)
    # 학생 이름, 평균, 등급을 보기 좋게 출력합니다.
    print(f"{student_data['name']} | 평균: {average:.1f} | 등급: {grade}")

# 학생 딕셔너리를 함수에 전달합니다.
print_student_report(student)

# 구분선을 출력합니다.
print("-" * 50)


