# 결과를 출력만 하는 함수를 정의합니다.
def add_print(a, b):
    # 계산한 값을 화면에 직접 출력합니다.
    print(a + b)

# 결과를 반환하는 함수를 정의합니다.
def add_return(a, b):
    # 계산한 값을 호출한 위치로 반환합니다.
    return a + b

# 출력만 하는 함수를 호출합니다.
add_print(3, 5)

# 반환하는 함수를 호출하고 결과를 변수에 저장합니다.
returned_value = add_return(3, 5)

# 반환값을 이용하여 추가 계산을 수행합니다.
print(f"반환값에 10을 더한 결과 = {returned_value + 10}")

