# 14. 전체 학생의 평균을 구하는 함수
# ------------------------------------------------------------

# 여러 학생의 개인 평균을 다시 평균내는 함수를 정의합니다.
def get_class_average(student_list):
    # 학생별 평균의 합을 저장할 변수를 0으로 초기화합니다.
    total_average = 0
    # 학생 리스트의 학생 정보를 하나씩 반복합니다.
    for student_data in student_list:
        # 현재 학생의 평균을 계산합니다.
        student_average = get_average(student_data["scores"])
        # 현재 학생의 평균을 누적합니다.
        total_average += student_average
    # 학생 평균의 합을 학생 수로 나누어 전체 평균을 반환합니다.
    return total_average / len(student_list)

# 전체 학생의 평균을 계산합니다.
class_average = get_class_average(students)

# 전체 평균을 소수점 첫째 자리까지 출력합니다.
print(f"전체 학생 평균 = {class_average:.1f}")

