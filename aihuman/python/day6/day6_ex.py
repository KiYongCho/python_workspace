# 11. 전역변수 변경보다 매개변수와 return을 활용하기
# ------------------------------------------------------------

# 전달받은 count 값에 1을 더해 반환하는 함수를 정의합니다.
def increase(count):
    # 기존 값을 직접 전역에서 변경하지 않고 새로운 값을 반환합니다.
    return count + 1

# 현재 횟수를 0으로 설정합니다.
current_count = 0

# 현재 횟수를 함수에 전달하고 증가된 값을 다시 저장합니다.
current_count = increase(current_count)

# 증가된 값을 출력합니다.
print(f"현재 횟수 = {current_count}")

# 다시 함수를 호출하여 값을 한 번 더 증가시킵니다.
current_count = increase(current_count)

# 두 번 증가된 값을 출력합니다.
print(f"현재 횟수 = {current_count}")

# 구분선을 출력합니다.
print("-" * 50)


