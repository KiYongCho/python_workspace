# a와 b 두 개의 매개변수를 받는 add 함수를 정의합니다.
def add(a, b):
    # 두 값을 더한 결과를 result 변수에 저장합니다.
    result = a + b
    # 계산 결과를 함수 호출 위치로 반환합니다.
    return result

# 10과 20을 인수로 전달하고 반환값을 sum_result 변수에 저장합니다.
sum_result = add(10, 20)

# 반환받은 값을 화면에 출력합니다.
print(f"10 + 20 = {sum_result}")

# 반환값을 다른 계산에 다시 사용할 수 있습니다.
print(f"반환값의 2배 = {sum_result * 2}")

# 구분선을 출력합니다.
print("-" * 50)


