# Application 과제 풀이: A~F 성적 등급 판정기

score = int(input("점수: "))  # 점수를 입력받아 정수로 변환합니다.

if score < 0 or score > 100:  # 점수가 정상 범위 0~100을 벗어났는지 확인합니다.
    print("입력 오류")  # 범위를 벗어난 경우 오류 메시지를 출력합니다.
elif score >= 90:  # 정상 범위에서 90점 이상인지 가장 먼저 확인합니다.
    print("등급: A")  # 90~100점이면 A를 출력합니다.
elif score >= 80:  # 90점 미만이면서 80점 이상인지 확인합니다.
    print("등급: B")  # 80~89점이면 B를 출력합니다.
elif score >= 70:  # 80점 미만이면서 70점 이상인지 확인합니다.
    print("등급: C")  # 70~79점이면 C를 출력합니다.
elif score >= 60:  # 70점 미만이면서 60점 이상인지 확인합니다.
    print("등급: D")  # 60~69점이면 D를 출력합니다.
else:  # 정상 범위에서 60점 미만인 경우입니다.
    print("등급: F")  # 0~59점이면 F를 출력합니다.
