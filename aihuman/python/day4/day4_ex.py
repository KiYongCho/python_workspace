# day4_ex.py
# AI휴먼 Day 4 실습
# 주제: 조건문으로 프로그램의 흐름 제어하기
# 핵심: 조건식, Boolean, if, elif, else, 논리 연산자, 중첩조건

# ------------------------------------------------------------
# 1. Boolean과 비교 연산자
# ------------------------------------------------------------

score = 85  # 학생의 점수를 정수형 변수 score에 저장합니다.

print(score >= 80)  # score가 80 이상인지 비교하고 True/False를 출력합니다.
print(score < 60)  # score가 60 미만인지 비교하고 True/False를 출력합니다.
print(score == 85)  # score가 85와 같은지 비교하고 True/False를 출력합니다.
print(score != 85)  # score가 85와 다른지 비교하고 True/False를 출력합니다.

# ------------------------------------------------------------
# 2. 가장 기본적인 if문
# ------------------------------------------------------------

temperature = 31  # 현재 기온을 정수형 변수에 저장합니다.

if temperature >= 30:  # 기온이 30도 이상인지 확인합니다.
    print("폭염 주의")  # 조건이 True일 때만 이 문장을 출력합니다.

print("기온 확인 완료")  # if문 바깥이므로 조건과 관계없이 실행됩니다.

# ------------------------------------------------------------
# 3. if - else로 두 가지 경우 처리
# ------------------------------------------------------------

score = 75  # 새로운 점수 75를 score에 저장합니다.

if score >= 80:  # 점수가 80 이상인지 판단합니다.
    print("PASS")  # 조건이 True이면 PASS를 출력합니다.
else:  # 위 조건이 False인 경우를 처리합니다.
    print("RETRY")  # 점수가 80 미만이면 RETRY를 출력합니다.

# ------------------------------------------------------------
# 4. if - elif - else로 여러 구간 처리
# ------------------------------------------------------------

score = 85  # 등급을 판정할 점수를 저장합니다.

if score >= 90:  # 가장 높은 기준인 90점 이상부터 확인합니다.
    grade = "A"  # 조건이 True이면 등급을 A로 저장합니다.
elif score >= 80:  # 90점 미만인 값 중에서 80점 이상인지 확인합니다.
    grade = "B"  # 조건이 True이면 등급을 B로 저장합니다.
elif score >= 70:  # 80점 미만인 값 중에서 70점 이상인지 확인합니다.
    grade = "C"  # 조건이 True이면 등급을 C로 저장합니다.
elif score >= 60:  # 70점 미만인 값 중에서 60점 이상인지 확인합니다.
    grade = "D"  # 조건이 True이면 등급을 D로 저장합니다.
else:  # 앞의 모든 조건이 False인 경우를 처리합니다.
    grade = "F"  # 60점 미만이면 등급을 F로 저장합니다.

print(f"점수: {score}, 등급: {grade}")  # 점수와 판정된 등급을 출력합니다.

# ------------------------------------------------------------
# 5. 논리 연산자 and
# ------------------------------------------------------------

score = 82  # 학생의 점수를 저장합니다.
attendance = 91  # 학생의 출석률을 저장합니다.

if score >= 70 and attendance >= 80:  # 점수와 출석률 조건을 모두 만족하는지 확인합니다.
    print("최종 판정: PASS")  # 두 조건이 모두 True이면 PASS를 출력합니다.
else:  # 두 조건 중 하나라도 만족하지 못한 경우를 처리합니다.
    print("최종 판정: FAIL")  # 최종 결과를 FAIL로 출력합니다.

# ------------------------------------------------------------
# 6. 논리 연산자 or
# ------------------------------------------------------------

score = 95  # 시험 점수를 저장합니다.
project_score = 72  # 프로젝트 점수를 저장합니다.

if score >= 90 or project_score >= 90:  # 두 평가 중 하나라도 90 이상인지 확인합니다.
    print("우수 항목이 있습니다.")  # 하나 이상의 조건이 True이면 출력합니다.
else:  # 두 평가 모두 90 미만인 경우를 처리합니다.
    print("우수 항목이 없습니다.")  # 해당 안내문을 출력합니다.

# ------------------------------------------------------------
# 7. 논리 연산자 not
# ------------------------------------------------------------

is_login = False  # 로그인 여부를 Boolean 값으로 저장합니다.

if not is_login:  # 로그인 상태가 False인지 확인합니다.
    print("로그인이 필요합니다.")  # 로그인하지 않았다면 안내문을 출력합니다.
else:  # 로그인 상태가 True인 경우를 처리합니다.
    print("서비스를 이용할 수 있습니다.")  # 로그인 사용자에게 안내문을 출력합니다.

# ------------------------------------------------------------
# 8. 중첩 조건문
# ------------------------------------------------------------

score = 85  # 점수를 저장합니다.
attendance = 75  # 출석률을 저장합니다.

if score >= 70:  # 먼저 점수 조건을 확인합니다.
    if attendance >= 80:  # 점수 조건을 통과한 경우 출석률을 추가로 확인합니다.
        print("PASS")  # 점수와 출석률을 모두 만족하면 PASS를 출력합니다.
    else:  # 점수는 만족하지만 출석률이 부족한 경우입니다.
        print("FAIL: 출석률 부족")  # 실패 이유를 출력합니다.
else:  # 점수 조건을 만족하지 못한 경우입니다.
    print("FAIL: 점수 부족")  # 실패 이유를 출력합니다.

# ------------------------------------------------------------
# 9. 입력값과 조건문 연결
# ------------------------------------------------------------

user_score = int(input("점수를 입력하세요(0~100): "))  # 문자열 입력을 정수로 변환합니다.

if user_score < 0 or user_score > 100:  # 점수가 정상 범위를 벗어났는지 확인합니다.
    print("입력 오류: 점수는 0~100 사이여야 합니다.")  # 잘못된 범위를 안내합니다.
elif user_score >= 60:  # 정상 범위의 점수 중 60점 이상인지 확인합니다.
    print("PASS")  # 60점 이상이면 PASS를 출력합니다.
else:  # 정상 범위이지만 60점 미만인 경우입니다.
    print("RETRY")  # 60점 미만이면 RETRY를 출력합니다.

# ------------------------------------------------------------
# 10. 대표 실습: 조건 기반 성적 판정기
# ------------------------------------------------------------

score = int(input("성적 점수(0~100): "))  # 성적 점수를 입력받아 정수로 변환합니다.
attendance = int(input("출석률(0~100): "))  # 출석률을 입력받아 정수로 변환합니다.

if score < 0 or score > 100:  # 성적 점수가 정상 범위를 벗어났는지 확인합니다.
    print("입력 오류: 성적 점수는 0~100 사이여야 합니다.")  # 성적 점수 오류 메시지를 출력합니다.
elif attendance < 0 or attendance > 100:  # 출석률이 정상 범위를 벗어났는지 확인합니다.
    print("입력 오류: 출석률은 0~100 사이여야 합니다.")  # 출석률 오류 메시지를 출력합니다.
else:  # 두 입력값이 모두 정상 범위인 경우입니다.
    if score >= 90:  # 점수가 90점 이상인지 확인합니다.
        grade = "A"  # 등급을 A로 저장합니다.
    elif score >= 80:  # 90점 미만이면서 80점 이상인지 확인합니다.
        grade = "B"  # 등급을 B로 저장합니다.
    elif score >= 70:  # 80점 미만이면서 70점 이상인지 확인합니다.
        grade = "C"  # 등급을 C로 저장합니다.
    elif score >= 60:  # 70점 미만이면서 60점 이상인지 확인합니다.
        grade = "D"  # 등급을 D로 저장합니다.
    else:  # 60점 미만인 경우입니다.
        grade = "F"  # 등급을 F로 저장합니다.

    if score >= 90 and attendance >= 95:  # 점수와 출석률이 우수 합격 기준을 모두 만족하는지 확인합니다.
        result = "우수 합격"  # 우수 합격 결과를 저장합니다.
        reason = "점수와 출석률 모두 우수"  # 판정 이유를 저장합니다.
    elif score >= 70 and attendance >= 80:  # 일반 합격 기준을 모두 만족하는지 확인합니다.
        result = "합격"  # 일반 합격 결과를 저장합니다.
        reason = "점수와 출석률 기준 충족"  # 판정 이유를 저장합니다.
    elif attendance < 80:  # 출석률이 합격 기준보다 낮은지 확인합니다.
        result = "불합격"  # 불합격 결과를 저장합니다.
        reason = "출석률 미달"  # 판정 이유를 저장합니다.
    else:  # 출석률은 기준을 만족하지만 점수가 부족한 경우입니다.
        result = "불합격"  # 불합격 결과를 저장합니다.
        reason = "점수 미달"  # 판정 이유를 저장합니다.

    print(f"등급: {grade}")  # 계산한 성적 등급을 출력합니다.
    print(f"최종 판정: {result}")  # 최종 합격 여부를 출력합니다.
    print(f"판정 이유: {reason}")  # 최종 판정의 이유를 출력합니다.
