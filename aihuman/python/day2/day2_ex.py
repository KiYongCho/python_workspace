course_name = "AI휴먼"  # 과정명을 문자열 변수에 저장합니다.
learner_name = "홍길동"  # 실습자가 자신의 이름으로 변경할 수 있는 변수입니다.
learner_age = 22  # 실습자가 자신의 나이로 변경할 수 있는 정수 변수입니다.
target_job = "AI 서비스 개발자"  # 실습자가 자신의 희망직무로 변경할 수 있는 문자열 변수입니다.
current_level = "입문"  # 현재 Python 학습 수준을 문자열로 표현합니다.
study_hours_today = 8.0  # 오늘 학습시간을 실수형 값으로 저장합니다.
completed_day2 = True  # Day 2 실습 완료 여부를 bool 값으로 저장합니다.

print("\n=== 나의 AI휴먼 학습 프로필 ===")  # 최종 산출물의 제목을 출력합니다.
print(f"과정명: {course_name}")  # 과정명을 출력합니다.
print(f"이름: {learner_name}")  # 학습자 이름을 출력합니다.
print(f"나이: {learner_age}세")  # 학습자 나이를 출력합니다.
print(f"희망직무: {target_job}")  # 희망직무를 출력합니다.
print(f"현재 수준: {current_level}")  # 현재 학습 수준을 출력합니다.
print(f"오늘 학습시간: {study_hours_today}시간")  # 실수형 학습시간을 출력합니다.
print(f"Day 2 완료 여부: {completed_day2}")  # 불리언 형태의 완료 여부를 출력합니다.

print("\n=== 최종 자료형 점검 ===")  # 마지막으로 각 변수의 자료형을 점검합니다.
print("learner_name:", type(learner_name))  # 이름이 str 자료형인지 확인합니다.
print("learner_age:", type(learner_age))  # 나이가 int 자료형인지 확인합니다.
print("target_job:", type(target_job))  # 희망직무가 str 자료형인지 확인합니다.
print("study_hours_today:", type(study_hours_today))  # 학습시간이 float 자료형인지 확인합니다.
print("completed_day2:", type(completed_day2))  # 완료 여부가 bool 자료형인지 확인합니다.

print("\n=== Day 2 실습 종료 ===")  # 모든 실습 코드가 정상적으로 끝났음을 출력합니다.
