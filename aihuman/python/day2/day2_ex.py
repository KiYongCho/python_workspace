# ------------------------------------------------------------
# 1. Python 코드의 기본 실행 흐름 확인
# ------------------------------------------------------------

print("=== AI휴먼 Day 2 실습 시작 ===")  # print() 함수로 프로그램 시작 메시지를 콘솔에 출력합니다.
print("Python 코드는 기본적으로 위에서 아래 순서로 실행됩니다.")  # 두 번째 출력문이 첫 번째 출력문 다음에 실행되는지 확인합니다.

# ------------------------------------------------------------
# 2. 리터럴과 변수 만들기
# ------------------------------------------------------------

name = "홍길동"  # 문자열(str) 값 "홍길동"을 name이라는 변수 이름으로 사용합니다.
age = 22  # 정수(int) 값 22를 age라는 변수 이름으로 사용합니다.
score = 85.5  # 실수(float) 값 85.5를 score라는 변수 이름으로 사용합니다.
is_job_seeker = True  # 불리언(bool) 값 True를 취업준비 여부를 나타내는 변수에 저장합니다.
portfolio_url = None  # 아직 포트폴리오 주소가 없다는 의미로 None 값을 저장합니다.

print(name)  # name 변수가 가리키는 문자열 값을 출력합니다.
print(age)  # age 변수가 가리키는 정수 값을 출력합니다.
print(score)  # score 변수가 가리키는 실수 값을 출력합니다.
print(is_job_seeker)  # is_job_seeker 변수가 가리키는 불리언 값을 출력합니다.
print(portfolio_url)  # portfolio_url 변수가 가리키는 None 값을 출력합니다.

# ------------------------------------------------------------
# 3. type()으로 자료형 확인하기
# ------------------------------------------------------------

print("\n=== 자료형 확인 ===")  # 줄을 한 번 바꾼 뒤 자료형 확인 구역의 제목을 출력합니다.
print(type(name))  # name이 가리키는 객체의 자료형이 str인지 확인합니다.
print(type(age))  # age가 가리키는 객체의 자료형이 int인지 확인합니다.
print(type(score))  # score가 가리키는 객체의 자료형이 float인지 확인합니다.
print(type(is_job_seeker))  # is_job_seeker가 가리키는 객체의 자료형이 bool인지 확인합니다.
print(type(portfolio_url))  # portfolio_url이 가리키는 객체의 자료형이 NoneType인지 확인합니다.

# ------------------------------------------------------------
# 4. 같은 변수 이름에 새로운 값 다시 대입하기
# ------------------------------------------------------------

status = "준비중"  # status라는 변수 이름을 문자열 "준비중"과 연결합니다.
print("처음 상태:", status)  # 처음 저장된 상태 값을 출력합니다.

status = "학습중"  # 같은 status 변수 이름에 새로운 문자열 "학습중"을 다시 대입합니다.
print("변경 상태:", status)  # 재대입 이후에는 새로운 값이 출력되는지 확인합니다.

# ------------------------------------------------------------
# 5. 동적 타이핑의 간단한 예
# ------------------------------------------------------------

data = 100  # data라는 이름이 먼저 정수(int) 객체 100을 가리키게 합니다.
print("data 값:", data)  # 현재 data의 값을 출력합니다.
print("data 자료형:", type(data))  # 현재 data의 자료형이 int인지 확인합니다.

data = "백"  # 같은 data라는 이름이 이번에는 문자열(str) 객체 "백"을 가리키게 합니다.
print("변경된 data 값:", data)  # 재대입된 문자열 값을 출력합니다.
print("변경된 data 자료형:", type(data))  # data가 이제 str 자료형 객체를 가리키는지 확인합니다.

# ------------------------------------------------------------
# 6. 의미가 분명한 변수명 사용하기
# ------------------------------------------------------------

student_name = "김AI"  # student_name은 수강생 이름이라는 의미가 드러나는 변수명입니다.
student_age = 24  # student_age는 수강생 나이를 저장하는 정수형 변수입니다.
desired_job = "데이터 분석가"  # desired_job은 희망직무를 저장하는 문자열 변수입니다.
python_experience_years = 0.5  # Python 경험기간을 실수(float)로 표현합니다.
is_major = False  # 전공자 여부를 bool 값으로 표현하며 여기서는 비전공자를 의미하는 False를 저장합니다.

# ------------------------------------------------------------
# 7. f-string으로 개인 프로필 출력하기
# ------------------------------------------------------------

print("\n=== 개인 프로필 ===")  # 개인 프로필 출력 구역의 제목을 출력합니다.
print(f"이름: {student_name}")  # f-string의 중괄호 안에 student_name의 값을 넣어 출력합니다.
print(f"나이: {student_age}세")  # 정수형 변수도 f-string 안에서 문자열과 함께 출력할 수 있습니다.
print(f"희망직무: {desired_job}")  # 희망직무 문자열을 사람이 읽기 좋은 형태로 출력합니다.
print(f"Python 경험: {python_experience_years}년")  # 실수형 경험기간을 문자열 문장 안에 넣어 출력합니다.
print(f"전공자 여부: {is_major}")  # 불리언 값도 f-string으로 출력할 수 있습니다.

# ------------------------------------------------------------
# 8. 변수와 객체를 이해하기 위한 간단한 확인
# ------------------------------------------------------------

first_score = 90  # first_score라는 이름이 정수 객체 90을 가리킵니다.
second_score = first_score  # second_score에도 first_score가 가리키는 값 90을 사용하도록 대입합니다.

print("\n=== 변수 값 확인 ===")  # 변수 값 확인 구역의 제목을 출력합니다.
print("first_score:", first_score)  # first_score의 현재 값을 출력합니다.
print("second_score:", second_score)  # second_score의 현재 값을 출력합니다.
print("first_score 자료형:", type(first_score))  # first_score가 int 객체를 가리키는지 확인합니다.
print("second_score 자료형:", type(second_score))  # second_score 역시 int 객체를 가리키는지 확인합니다.

