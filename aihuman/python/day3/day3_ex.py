# day3_ex.py
# AI휴먼 Day 3 실습코드
# 주제: Python 연산자 · 입출력 · 형변환
# 목표: 입력 → 처리 → 출력 흐름으로 콘솔 주문 계산기를 완성합니다.


# =========================================================
# 1. 산술 연산자 기본 실습
# =========================================================

# 첫 번째 숫자를 정수형 변수에 저장합니다.
a = 10

# 두 번째 숫자를 정수형 변수에 저장합니다.
b = 3

# + 연산자로 두 수를 더합니다.
print("더하기:", a + b)

# - 연산자로 두 수를 뺍니다.
print("빼기:", a - b)

# * 연산자로 두 수를 곱합니다.
print("곱하기:", a * b)

# / 연산자로 두 수를 나눕니다.
print("나누기:", a / b)

# // 연산자로 나눗셈의 몫을 구합니다.
print("몫:", a // b)

# % 연산자로 나눗셈의 나머지를 구합니다.
print("나머지:", a % b)

# ** 연산자로 거듭제곱을 계산합니다.
print("거듭제곱:", a ** b)


# =========================================================
# 2. 연산자 우선순위 실습
# =========================================================

# 곱셈이 덧셈보다 먼저 계산됩니다.
result1 = 2 + 3 * 4

# 괄호 안의 덧셈을 먼저 계산합니다.
result2 = (2 + 3) * 4

# 두 계산 결과의 차이를 출력합니다.
print("우선순위 결과 1:", result1)

# 괄호를 사용한 계산 결과를 출력합니다.
print("우선순위 결과 2:", result2)


# =========================================================
# 3. 비교 연산자 실습
# =========================================================

# 10이 5보다 큰지 비교하면 True가 나옵니다.
print("10 > 5:", 10 > 5)

# 10과 5가 같은지 비교하면 False가 나옵니다.
print("10 == 5:", 10 == 5)

# 10과 5가 다른지 비교하면 True가 나옵니다.
print("10 != 5:", 10 != 5)

# 비교 결과가 bool 자료형인지 확인합니다.
comparison_result = 10 >= 5

# 비교 결과를 출력합니다.
print("비교 결과:", comparison_result)

# 비교 결과의 자료형을 출력합니다.
print("비교 결과 자료형:", type(comparison_result))


# =========================================================
# 4. 논리 연산자 실습
# =========================================================

# 나이가 20세 이상인지 비교합니다.
age_ok = 23 >= 20

# 점수가 80점 이상인지 비교합니다.
score_ok = 85 >= 80

# and는 두 조건이 모두 True일 때 True입니다.
print("AND 결과:", age_ok and score_ok)

# or는 두 조건 중 하나라도 True이면 True입니다.
print("OR 결과:", age_ok or score_ok)

# not은 True와 False를 반대로 바꿉니다.
print("NOT 결과:", not age_ok)


# =========================================================
# 5. input() 기본 실습
# =========================================================

# 사용자에게 이름을 입력받습니다.
name = input("이름을 입력하세요: ")

# 입력받은 이름을 출력합니다.
print("입력한 이름:", name)

# input()으로 받은 값의 자료형을 확인합니다.
print("이름의 자료형:", type(name))


# =========================================================
# 6. input()으로 받은 숫자의 자료형 확인
# =========================================================

# 사용자에게 나이를 입력받습니다.
age_text = input("나이를 입력하세요: ")

# 화면에서는 숫자처럼 보여도 실제 자료형은 str입니다.
print("입력한 나이:", age_text)

# input() 결과의 자료형이 str임을 확인합니다.
print("나이 입력값의 자료형:", type(age_text))


# =========================================================
# 7. 형변환(Type Casting) 실습
# =========================================================

# 문자열 형태의 나이를 int로 변환합니다.
age = int(age_text)

# 변환된 값을 출력합니다.
print("정수로 변환한 나이:", age)

# 변환 후 자료형이 int인지 확인합니다.
print("변환 후 자료형:", type(age))

# 문자열 형태의 실수 값을 준비합니다.
height_text = "173.5"

# 문자열을 float로 변환합니다.
height = float(height_text)

# float 변환 결과를 출력합니다.
print("키:", height)

# float 자료형인지 확인합니다.
print("키의 자료형:", type(height))


# =========================================================
# 8. 간단한 가격 × 수량 계산
# =========================================================

# 사용자에게 상품 가격을 입력받고 바로 int로 변환합니다.
price = int(input("상품 가격을 입력하세요: "))

# 사용자에게 수량을 입력받고 바로 int로 변환합니다.
quantity = int(input("수량을 입력하세요: "))

# 가격과 수량을 곱해서 총액을 계산합니다.
total = price * quantity

# f-string으로 계산 결과를 출력합니다.
print(f"총액: {total}원")

# 천 단위 쉼표를 적용하여 더 읽기 좋게 출력합니다.
print(f"총액(쉼표 적용): {total:,}원")


# =========================================================
# 9. 할인율을 포함한 주문 계산
# =========================================================

# 상품명을 문자열로 입력받습니다.
product = input("상품명을 입력하세요: ")

# 단가를 입력받고 정수로 변환합니다.
unit_price = int(input("단가를 입력하세요: "))

# 수량을 입력받고 정수로 변환합니다.
qty = int(input("구매 수량을 입력하세요: "))

# 할인율을 입력받고 실수로 변환합니다.
discount_rate = float(input("할인율(%)을 입력하세요: "))

# 할인 전 주문금액을 계산합니다.
subtotal = unit_price * qty

# 주문금액에 할인율을 적용해 할인금액을 계산합니다.
discount_amount = subtotal * discount_rate / 100

# 주문금액에서 할인금액을 빼서 최종 결제금액을 계산합니다.
final_amount = subtotal - discount_amount

# 구분선을 출력합니다.
print("=" * 40)

# 상품명을 출력합니다.
print(f"상품명: {product}")

# 주문금액을 소수점 없이 천 단위 쉼표로 출력합니다.
print(f"주문금액: {subtotal:,.0f}원")

# 할인율을 소수점 한 자리까지 출력합니다.
print(f"할인율: {discount_rate:.1f}%")

# 할인금액을 소수점 없이 천 단위 쉼표로 출력합니다.
print(f"할인금액: {discount_amount:,.0f}원")

# 최종 결제금액을 소수점 없이 천 단위 쉼표로 출력합니다.
print(f"최종 결제금액: {final_amount:,.0f}원")

# 구분선을 출력합니다.
print("=" * 40)


# =========================================================
# 10. 디버깅 연습: type()과 중간값 확인
# =========================================================

# 단가가 int 자료형인지 확인합니다.
print("unit_price 자료형:", type(unit_price))

# 수량이 int 자료형인지 확인합니다.
print("qty 자료형:", type(qty))

# 할인율이 float 자료형인지 확인합니다.
print("discount_rate 자료형:", type(discount_rate))

# 중간 계산값을 확인하여 계산 흐름을 추적합니다.
print("subtotal 중간값:", subtotal)

# 중간 계산값을 확인하여 계산 흐름을 추적합니다.
print("discount_amount 중간값:", discount_amount)


