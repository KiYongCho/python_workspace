# =========================================================
# 1. 정상 주문 영수증 계산
# =========================================================

# 상품명은 문자열이므로 별도의 형변환 없이 입력받습니다.
product = input("상품명: ")

# 단가는 금액 계산에 사용하므로 정수로 변환합니다.
unit_price = int(input("단가: "))

# 수량은 개수이므로 정수로 변환합니다.
quantity = int(input("수량: "))

# 할인율은 소수점 입력 가능성을 고려해 실수로 변환합니다.
discount_rate = float(input("할인율(%): "))

# 부가세율도 소수점 입력 가능성을 고려해 실수로 변환합니다.
tax_rate = float(input("부가세율(%): "))

# 단가와 수량을 곱하여 할인 전 주문금액을 계산합니다.
subtotal = unit_price * quantity

# 백분율로 입력된 할인율을 실제 금액으로 계산합니다.
discount_amount = subtotal * discount_rate / 100

# 주문금액에서 할인금액을 빼 할인 후 금액을 계산합니다.
after_discount = subtotal - discount_amount

# 할인 후 금액을 기준으로 부가세를 계산합니다.
tax_amount = after_discount * tax_rate / 100

# 할인 후 금액에 부가세를 더해 최종 결제금액을 계산합니다.
final_amount = after_discount + tax_amount

# 영수증 시작 구분선을 출력합니다.
print("=" * 45)

# 영수증 제목을 출력합니다.
print("[AI휴먼 주문 영수증]")

# 상품명을 출력합니다.
print(f"상품명: {product}")

# 주문금액을 소수점 없이 천 단위 쉼표로 출력합니다.
print(f"주문금액: {subtotal:,.0f}원")

# 할인율을 소수점 한 자리까지 출력합니다.
print(f"할인율: {discount_rate:.1f}%")

# 할인금액을 출력합니다.
print(f"할인금액: {discount_amount:,.0f}원")

# 할인 후 금액을 출력합니다.
print(f"할인 후 금액: {after_discount:,.0f}원")

# 부가세율을 소수점 한 자리까지 출력합니다.
print(f"부가세율: {tax_rate:.1f}%")

# 부가세 금액을 출력합니다.
print(f"부가세: {tax_amount:,.0f}원")

# 최종 결제금액을 출력합니다.
print(f"최종 결제금액: {final_amount:,.0f}원")

# 영수증 끝 구분선을 출력합니다.
print("=" * 45)


