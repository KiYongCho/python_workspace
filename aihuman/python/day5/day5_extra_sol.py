# Python 별찍기 풀이
# 공통 조건:
# - 문자열 반복 연산('*' * n, ' ' * n)을 사용하지 않습니다.
# - for문, 중첩 for문, if문을 사용합니다.


# ============================================================
# 1. 왼쪽 직각삼각형
# ============================================================

n = 5

for i in range(1, n + 1):
    for j in range(i):
        print('*', end='')
    print()

print()


# ============================================================
# 2. 역직각삼각형
# ============================================================

n = 5

for i in range(n, 0, -1):
    for j in range(i):
        print('*', end='')
    print()

print()


# ============================================================
# 3. 오른쪽 정렬 직각삼각형
# ============================================================

n = 5

for i in range(1, n + 1):

    # 공백 출력
    for j in range(n - i):
        print(' ', end='')

    # 별 출력
    for j in range(i):
        print('*', end='')

    print()

print()


# ============================================================
# 4. 피라미드
# ============================================================

n = 5

for i in range(1, n + 1):

    # 왼쪽 공백
    for j in range(n - i):
        print(' ', end='')

    # 별
    for j in range(2 * i - 1):
        print('*', end='')

    print()

print()


# ============================================================
# 5. 역피라미드
# ============================================================

n = 5

for i in range(1, n + 1):

    # 왼쪽 공백
    for j in range(i - 1):
        print(' ', end='')

    # 별
    for j in range(2 * (n - i) + 1):
        print('*', end='')

    print()

print()


# ============================================================
# 6. 다이아몬드
# ============================================================

n = 5

# 위쪽
for i in range(1, n + 1):

    for j in range(n - i):
        print(' ', end='')

    for j in range(2 * i - 1):
        print('*', end='')

    print()

# 아래쪽
for i in range(n - 1, 0, -1):

    for j in range(n - i):
        print(' ', end='')

    for j in range(2 * i - 1):
        print('*', end='')

    print()

print()


# ============================================================
# 7. 속이 빈 피라미드
# ============================================================

n = 5

for i in range(1, n + 1):

    # 왼쪽 공백
    for j in range(n - i):
        print(' ', end='')

    # 피라미드 내부
    for j in range(1, 2 * i):

        # 마지막 행은 모두 별
        if i == n:
            print('*', end='')

        # 양쪽 테두리
        elif j == 1 or j == 2 * i - 1:
            print('*', end='')

        else:
            print(' ', end='')

    print()

print()


# ============================================================
# 8. 속이 빈 사각형
# ============================================================

n = 5

for i in range(n):

    for j in range(n):

        # 위쪽, 아래쪽, 왼쪽, 오른쪽 테두리
        if i == 0 or i == n - 1 or j == 0 or j == n - 1:
            print('*', end='')
        else:
            print(' ', end='')

    print()

print()


# ============================================================
# 9. X자
# ============================================================

n = 9

for i in range(n):

    for j in range(n):

        # 왼쪽 위 -> 오른쪽 아래 대각선
        # 오른쪽 위 -> 왼쪽 아래 대각선
        if j == i or j == n - i - 1:
            print('*', end='')
        else:
            print(' ', end='')

    print()

print()


# ============================================================
# 10. 속이 빈 모래시계 모양
# ============================================================

n = 5

# 위쪽
for i in range(n):

    # 왼쪽 공백
    print(' ' * i, end='')

    width = 2 * (n - i) - 1

    for j in range(width):

        if i == 0:
            print('*', end='')

        elif j == 0 or j == width - 1:
            print('*', end='')

        else:
            print(' ', end='')

    print()


# 아래쪽
for i in range(n - 2, -1, -1):

    print(' ' * i, end='')

    width = 2 * (n - i) - 1

    for j in range(width):

        if i == 0:
            print('*', end='')

        elif j == 0 or j == width - 1:
            print('*', end='')

        else:
            print(' ', end='')

    print()