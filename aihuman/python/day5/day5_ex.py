# ------------------------------------------------------------
# 1. for문으로 여러 값 순서대로 출력하기
# ------------------------------------------------------------

# 여러 점수를 하나의 리스트에 저장합니다.
scores = [72, 88, 95, 61]

# 안내 문장을 출력합니다.
print("[1] 점수 목록 출력")

# scores 리스트에서 점수를 하나씩 꺼내 score 변수에 저장합니다.
for score in scores:
    # 현재 반복에서 꺼낸 점수를 출력합니다.
    print(score)

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 2. for문과 조건문을 함께 사용하기
# ------------------------------------------------------------

# 안내 문장을 출력합니다.
print("[2] PASS / RETRY 판정")

# scores 리스트의 모든 점수를 하나씩 반복합니다.
for score in scores:
    # 점수가 80점 이상인지 확인합니다.
    if score >= 80:
        # 조건이 참이면 PASS를 출력합니다.
        print(score, "PASS")
    # 80점 이상이 아닌 경우를 처리합니다.
    else:
        # 조건이 거짓이면 RETRY를 출력합니다.
        print(score, "RETRY")

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 3. range()로 정해진 횟수 반복하기
# ------------------------------------------------------------

# 안내 문장을 출력합니다.
print("[3] range() 기본 사용")

# range(5)는 0부터 4까지의 정수를 만듭니다.
for i in range(5):
    # 현재 숫자를 출력합니다.
    print("i =", i)

# 구분을 위해 빈 줄을 출력합니다.
print()

# 안내 문장을 출력합니다.
