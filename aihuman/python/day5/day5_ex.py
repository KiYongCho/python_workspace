# range(1, 6)은 1부터 5까지의 정수를 만듭니다.
for number in range(1, 6):
    # 현재 숫자를 출력합니다.
    print(number)

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 4. while문으로 조건이 참인 동안 반복하기
# ------------------------------------------------------------

# 반복에 사용할 count 변수를 1로 시작합니다.
count = 1

# 안내 문장을 출력합니다.
print("[5] while문으로 1부터 5까지 출력")

# count가 5 이하인 동안 반복합니다.
while count <= 5:
    # 현재 count 값을 출력합니다.
    print(count)
    # 다음 반복을 위해 count를 1 증가시킵니다.
    count += 1

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 5. 리스트의 합계를 반복문으로 계산하기
# ------------------------------------------------------------

# 합계를 저장할 변수를 0으로 초기화합니다.
total = 0

# scores 리스트의 모든 점수를 하나씩 반복합니다.
for score in scores:
    # 현재 점수를 total에 누적합니다.
    total += score

# 계산된 합계를 출력합니다.
print("[6] 점수 합계:", total)

# 점수의 개수로 합계를 나누어 평균을 계산합니다.
average = total / len(scores)

# 평균을 소수점 둘째 자리까지 출력합니다.
print(f"점수 평균: {average:.2f}")

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 6. 합격자 수를 반복문으로 계산하기
# ------------------------------------------------------------

# 합격자 수를 저장할 변수를 0으로 초기화합니다.
pass_count = 0

# scores 리스트의 점수를 하나씩 반복합니다.
for score in scores:
    # 현재 점수가 80점 이상인지 확인합니다.
    if score >= 80:
        # 합격 조건을 만족하면 합격자 수를 1 증가시킵니다.
        pass_count += 1

# 합격자 수를 출력합니다.
print("[7] 합격자 수:", pass_count)

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 7. 최고점을 반복문으로 직접 찾기
# ------------------------------------------------------------

# 첫 번째 점수를 현재 최고점으로 저장합니다.
highest = scores[0]

# scores 리스트의 점수를 하나씩 반복합니다.
for score in scores:
    # 현재 점수가 저장된 최고점보다 큰지 확인합니다.
    if score > highest:
        # 더 큰 점수를 발견하면 최고점을 교체합니다.
        highest = score

# 최종 최고점을 출력합니다.
print("[8] 최고점:", highest)

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 8. Dictionary에 학생 이름과 점수 저장하기
# ------------------------------------------------------------

# 학생 이름을 Key, 점수를 Value로 저장합니다.
students = {
    "민수": 72,
    "지연": 88,
    "준호": 95,
    "서연": 61,
}

# 안내 문장을 출력합니다.
print("[9] 학생 이름과 점수 출력")

# items()를 사용해 이름과 점수를 함께 하나씩 꺼냅니다.
for name, score in students.items():
    # 현재 학생의 이름과 점수를 출력합니다.
    print(name, score)

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 9. 학생별 등급 판정하기
# ------------------------------------------------------------

# 안내 문장을 출력합니다.
print("[10] 학생별 등급표")

# 학생 정보를 이름과 점수로 하나씩 반복합니다.
for name, score in students.items():
    # 90점 이상인지 확인합니다.
    if score >= 90:
        # 90점 이상이면 A 등급을 저장합니다.
        grade = "A"
    # 80점 이상인지 확인합니다.
    elif score >= 80:
        # 80점 이상 90점 미만이면 B 등급을 저장합니다.
        grade = "B"
    # 70점 이상인지 확인합니다.
    elif score >= 70:
        # 70점 이상 80점 미만이면 C 등급을 저장합니다.
        grade = "C"
    # 앞의 조건에 해당하지 않는 경우를 처리합니다.
    else:
        # 70점 미만이면 D 등급을 저장합니다.
        grade = "D"

    # 학생 이름, 점수, 등급을 한 줄로 출력합니다.
    print(f"{name}: {score}점 / {grade}등급")

# 구분을 위해 빈 줄을 출력합니다.
print()


# ------------------------------------------------------------
# 10. 대표 실습: 학생 성적 반복 처리 프로그램
# ------------------------------------------------------------

# 전체 합계를 저장할 변수를 0으로 초기화합니다.
student_total = 0

# 합격자 수를 저장할 변수를 0으로 초기화합니다.
student_pass_count = 0

# 최고점 학생을 저장할 변수를 빈 문자열로 초기화합니다.
top_name = ""

# 최고점을 비교하기 위해 -1로 초기화합니다.
top_score = -1

# 결과표 제목을 출력합니다.
print("[11] 학생 성적 반복 처리 프로그램")

# 표의 구분선을 출력합니다.
print("-" * 36)

# 학생 Dictionary에서 이름과 점수를 하나씩 꺼냅니다.
for name, score in students.items():
    # 현재 점수를 전체 합계에 더합니다.
    student_total += score

    # 현재 점수가 80점 이상인지 확인합니다.
    if score >= 80:
        # 합격자 수를 1 증가시킵니다.
        student_pass_count += 1

    # 현재 점수가 지금까지의 최고점보다 높은지 확인합니다.
    if score > top_score:
        # 최고점을 현재 점수로 바꿉니다.
        top_score = score
        # 최고점 학생 이름도 현재 학생으로 바꿉니다.
        top_name = name

    # 90점 이상인지 확인합니다.
    if score >= 90:
        # A 등급을 저장합니다.
        grade = "A"
    # 80점 이상인지 확인합니다.
    elif score >= 80:
        # B 등급을 저장합니다.
        grade = "B"
    # 70점 이상인지 확인합니다.
    elif score >= 70:
        # C 등급을 저장합니다.
        grade = "C"
    # 나머지 점수를 처리합니다.
    else:
        # D 등급을 저장합니다.
        grade = "D"

    # 80점 이상이면 PASS, 아니면 RETRY를 status에 저장합니다.
    status = "PASS" if score >= 80 else "RETRY"

    # 현재 학생의 결과를 출력합니다.
    print(f"{name:>2} | {score:>3}점 | {grade}등급 | {status}")

# 전체 학생 수를 구합니다.
student_count = len(students)

# 전체 평균을 계산합니다.
student_average = student_total / student_count

# 표의 구분선을 출력합니다.
print("-" * 36)

# 전체 학생 수를 출력합니다.
print("학생 수:", student_count)

# 전체 평균을 소수점 둘째 자리까지 출력합니다.
print(f"평균 점수: {student_average:.2f}")

# 합격자 수를 출력합니다.
print("합격자 수:", student_pass_count)

# 최고점 학생과 최고점을 출력합니다.
print(f"최고점: {top_name} / {top_score}점")

# 구분을 위해 빈 줄을 출력합니다.
print()


